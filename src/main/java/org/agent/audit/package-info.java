/**
 * 通用审计哈希链 —— <b>追加式、可发现篡改</b>的审计基础设施。
 *
 * <h2>为什么它是个独立的包，而不是放在 {@code org.agent.memory} 里</h2>
 * 记忆层的变更审计只是它的<b>第一个</b>用户。RAG-04 待做 #13「审计表 + 哈希链」要的是
 * 同一套机制 —— RAG-07 §A.3 的原话就是"与 #13 同一机制同一理由，<b>建议复用同一个实现</b>"。
 * 而 #13 至今仍在待做表里，所以本阶段实际上是在<b>建那个实现</b>。
 * <p>
 * 于是这个包里<b>不出现任何记忆相关的类型</b>：它只认"一串有序字段 + 上一条的哈希"，
 * 谁用它、用它审计什么，是调用方的事。#13 将来直接复用，不需要搬代码。
 *
 * <h2>⚠️ 它能做什么、不能做什么（讲清楚，否则是过度承诺）</h2>
 * <b>能</b>：任何一条历史记录被改动、被删除、被调换位置，都能被 {@code verify} 发现。
 * <p>
 * <b>不能</b>（三条诚实的边界）：
 * <ol>
 *   <li><b>不是防篡改（tamper-proof），是可发现篡改（tamper-evident）</b> ——
 *       有数据库写权限的人可以整条重算重写。链的价值是"改过就看得出来"，
 *       不是"改不了"</li>
 *   <li><b>应用层可以"不记"</b> —— 日志与业务行在同一个事务里，代码不写就没有。</li>
 *   <li><b>只在一个数据库内串行化</b> —— 靠追加时的 {@code SELECT ... FOR UPDATE}；
 *       多实例或多库之间的顺序它管不了</li>
 * </ol>
 * 真正的加固是"只授 INSERT / 触发器 / WORM 存储"，那属于运维，不在这一层。
 * 低成本的补偿是把每次追加后的 head hash 打一条 INFO 日志 —— 那等于一个外部锚点。
 *
 * <h2>⚠️ 四个必须讲清的实现细节（各自都有测试锁着）</h2>
 * <ol>
 *   <li><b>字段之间必须有分隔符</b>：无分隔拼接会让 {@code ("ab","c")} 与
 *       {@code ("a","bc")} 哈希相同 —— 哈希链的经典缺陷。</li>
 *   <li><b>哈希里不含物理主键 {@code id}</b>：本项目"主键不回填"的约定下，
 *       插入前根本拿不到它。行序由显式的 {@code prev_hash} 链给出，不靠 id</li>
 *   <li><b>时间戳由调用方提供、并进哈希</b>：若让数据库的
 *       {@code DEFAULT CURRENT_TIMESTAMP} 填，时间戳就<b>不受保护</b> ——
 *       改"何时记录的"不会有任何痕迹</li>
 *   <li><b>JSON 必须先规范化再哈希</b>：数据库的 JSON 列会重排对象键、抹掉空白，
 *       按"写入时那个字符串"算哈希，事后读回来重新校验会<b>假失败</b>。
 *       所以两边都过同一个 {@link org.agent.audit.AuditHashChain#canonicalJson}，
 *       由我们自己排键，不依赖数据库的顺序</li>
 * </ol>
 * {@code verify} 就在本包里，<b>不是测试专用品</b>：没有校验器的哈希链是装饰品 ——
 * "可发现篡改"这件事必须由一段能跑的代码定义，而不是由一句设计承诺定义。
 */
