package org.agent.memory.model;

/**
 * 语义记忆（L2）的可见范围。
 * <p>
 * 与 L1 的本质区别：L1 天生按 {@code session_id} 隔离，{@code scope} 这个概念在 L1 上不存在。
 * L2 是"跨会话"的，所以必须有一个<b>显式</b>的可见范围，否则"跨会话"就等于"对所有人可见"。
 *
 * <h2>⚠️ 本阶段只产生 {@link #USER}，且 {@link #GLOBAL} 读写皆拒</h2>
 * <ul>
 *   <li>{@link #USER} —— 唯一有自动写入路径的范围（owner_id 取自信封，模型无权提供）</li>
 *   <li>{@link #DEPT} —— <b>本阶段没有写入路径</b>（RAG-07 把"部门级晋升"写成需人工确认，
 *       与"只做两档"的决策冲突，归属阶段 4）。但<b>读分支照实现并用集成测试证明可读</b> ——
 *       否则权限分析不完整，也没法证明 {@code org_path} 精确匹配这条口径是对的</li>
 *   <li>{@link #GLOBAL} —— <b>声明但读写皆拒</b>（RAG-07 §七）。声明的意义是让
 *       {@code switch} 必须显式处理它 —— 若枚举里没有这一项，将来有人加"全局记忆"时
 *       会走 {@code default} 分支悄悄放行。<b>不存在的枚举值不可能被漏判，存在但被显式拒绝的才会</b></li>
 * </ul>
 */
public enum FactScope {

    /** 仅本人可见（owner_id 精确匹配）。本阶段唯一的自动写入范围 */
    USER,

    /** 同 {@code org_path} 可见（精确匹配，不做前缀匹配）。本阶段只读不写 */
    DEPT,

    /** 全局可见。⚠️ 本阶段读写皆拒 —— 保留枚举值是为了让"拒绝"这件事在代码里有落点 */
    GLOBAL
}
