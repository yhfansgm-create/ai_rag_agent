package org.agent.memory.model;

/**
 * 记忆变更的发起方。
 * <p>
 * <b>必须区分</b>，这不是可选的分类癖：在合规视角下<b>"模型自己改的"与"人改的"是两回事</b>。
 * 一处记忆变成了错误的客户偏好，追责时必须能一眼分出"是模型蒸馏错了"还是"有人手工改过"。
 * 这是评价轴里"审计"那一根的最小落点 —— 没有它，审计表只能证明"这条被改过"，
 * 证明不了"谁改的"。
 */
public enum MemoryActorType {

    /** 用户本人（阶段 4 的可查/可删接口会用它） */
    USER,

    /** 模型自动蒸馏写入 —— 本阶段所有写入都是这一种 */
    AUTO,

    /** 巡检任务（阶段 4 的 STALE 置位 / 过期归档） */
    SWEEP,

    /** 管理员（阶段 4 的人工修正） */
    ADMIN
}
